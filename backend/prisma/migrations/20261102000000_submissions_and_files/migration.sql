-- Batch 4B: file storage and student submissions.
--
--   stored_files         every uploaded file: a random storage key (never the student's filename),
--                        the original name, type, size and a SHA-256 checksum. Shared: other modules
--                        (media library, shop images) can use it too.
--   submissions          one row per (enrollment, assignment): its receipt (GSG-SUB-n), its status,
--                        and - when an instructor asked for changes - until when she may resubmit.
--   submission_versions  every version the student sent: when, whether it was Late, which published
--                        course version she answered, her link and note. NEVER changed afterwards.
--   submission_files     which files belong to which version. NEVER changed afterwards.
--
-- assignment_id and week_id have NO foreign key on purpose: they are ids of items in a PUBLISHED
-- course version, so restoring or discarding a draft can never touch a student's work.
-- Written by hand (sequence, CHECK rules, triggers); names follow Prisma's conventions.

-- ---------------------------------------------------------------------------
-- Receipts: GSG-SUB-1, GSG-SUB-2 ... generated by the database (race-free, only ever goes up).
-- ---------------------------------------------------------------------------
CREATE SEQUENCE "submission_ref_seq" START WITH 1;

CREATE FUNCTION "next_submission_reference"() RETURNS text AS $$
  SELECT 'GSG-SUB-' || nextval('submission_ref_seq')::text;
$$ LANGUAGE sql VOLATILE;

-- ---------------------------------------------------------------------------
-- stored_files
-- ---------------------------------------------------------------------------
CREATE TABLE "stored_files" (
  "id"             UUID           NOT NULL DEFAULT gen_random_uuid(),
  "storage_key"    VARCHAR(100)   NOT NULL,
  "original_name"  VARCHAR(200)   NOT NULL,
  "content_type"   VARCHAR(100)   NOT NULL,
  "size_bytes"     INTEGER        NOT NULL,
  "sha256"         CHAR(64)       NOT NULL,
  "uploaded_by_id" UUID,
  "created_at"     TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT "stored_files_pkey" PRIMARY KEY ("id"),
  CONSTRAINT "stored_files_size_check" CHECK ("size_bytes" > 0)
);

CREATE UNIQUE INDEX "stored_files_storage_key_key" ON "stored_files"("storage_key");

-- HAND-WRITTEN rule: what a stored file IS (its checksum, size, key) never changes.
CREATE FUNCTION "stored_files_refuse_update"() RETURNS trigger AS $$
BEGIN
  RAISE EXCEPTION 'stored_files rows cannot be changed';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER "stored_files_immutable"
  BEFORE UPDATE ON "stored_files"
  FOR EACH ROW EXECUTE FUNCTION "stored_files_refuse_update"();

-- ---------------------------------------------------------------------------
-- submissions
-- ---------------------------------------------------------------------------
CREATE TYPE "SubmissionStatus" AS ENUM ('SUBMITTED', 'REVIEWED', 'NEEDS_REVISION', 'COMPLETED');

CREATE TABLE "submissions" (
  "id"                  UUID               NOT NULL DEFAULT gen_random_uuid(),
  "reference"           VARCHAR(20)        NOT NULL DEFAULT "next_submission_reference"(),
  "enrollment_id"       UUID               NOT NULL,
  "assignment_id"       UUID               NOT NULL,
  "week_id"             UUID               NOT NULL,
  "status"              "SubmissionStatus" NOT NULL DEFAULT 'SUBMITTED',
  "revision_open_until" TIMESTAMPTZ(3),
  "created_at"          TIMESTAMPTZ(3)     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updated_at"          TIMESTAMPTZ(3)     NOT NULL,
  CONSTRAINT "submissions_pkey" PRIMARY KEY ("id"),
  -- A "resubmit until" date only makes sense while changes are being asked for.
  CONSTRAINT "submissions_revision_check"
    CHECK ("status" = 'NEEDS_REVISION' OR "revision_open_until" IS NULL)
);

CREATE UNIQUE INDEX "submissions_reference_key" ON "submissions"("reference");
CREATE UNIQUE INDEX "submissions_enrollment_id_assignment_id_key" ON "submissions"("enrollment_id", "assignment_id");
CREATE INDEX "submissions_enrollment_id_status_idx" ON "submissions"("enrollment_id", "status");
CREATE INDEX "submissions_assignment_id_status_idx" ON "submissions"("assignment_id", "status");

ALTER TABLE "submissions"
  ADD CONSTRAINT "submissions_enrollment_id_fkey"
    FOREIGN KEY ("enrollment_id") REFERENCES "enrollments"("id") ON DELETE RESTRICT ON UPDATE CASCADE;

-- ---------------------------------------------------------------------------
-- submission_versions  (a version, once sent, is read-only)
-- ---------------------------------------------------------------------------
CREATE TABLE "submission_versions" (
  "id"            UUID           NOT NULL DEFAULT gen_random_uuid(),
  "submission_id" UUID           NOT NULL,
  "number"        INTEGER        NOT NULL,
  "course_version" INTEGER       NOT NULL,
  "is_late"       BOOLEAN        NOT NULL,
  "link_url"      VARCHAR(2000),
  "note"          VARCHAR(2000),
  "created_at"    TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT "submission_versions_pkey" PRIMARY KEY ("id"),
  CONSTRAINT "submission_versions_number_check" CHECK ("number" BETWEEN 1 AND 25),
  CONSTRAINT "submission_versions_course_version_check" CHECK ("course_version" >= 1)
);

CREATE UNIQUE INDEX "submission_versions_submission_id_number_key" ON "submission_versions"("submission_id", "number");

ALTER TABLE "submission_versions"
  ADD CONSTRAINT "submission_versions_submission_id_fkey"
    FOREIGN KEY ("submission_id") REFERENCES "submissions"("id") ON DELETE RESTRICT ON UPDATE CASCADE;

-- ---------------------------------------------------------------------------
-- submission_files  (also read-only once written)
-- ---------------------------------------------------------------------------
CREATE TABLE "submission_files" (
  "id"         UUID    NOT NULL DEFAULT gen_random_uuid(),
  "version_id" UUID    NOT NULL,
  "file_id"    UUID    NOT NULL,
  "position"   INTEGER NOT NULL,
  CONSTRAINT "submission_files_pkey" PRIMARY KEY ("id"),
  CONSTRAINT "submission_files_position_check" CHECK ("position" BETWEEN 1 AND 5)
);

CREATE UNIQUE INDEX "submission_files_version_id_position_key" ON "submission_files"("version_id", "position");
CREATE UNIQUE INDEX "submission_files_version_id_file_id_key" ON "submission_files"("version_id", "file_id");
CREATE INDEX "submission_files_file_id_idx" ON "submission_files"("file_id");

ALTER TABLE "submission_files"
  ADD CONSTRAINT "submission_files_version_id_fkey"
    FOREIGN KEY ("version_id") REFERENCES "submission_versions"("id") ON DELETE RESTRICT ON UPDATE CASCADE,
  ADD CONSTRAINT "submission_files_file_id_fkey"
    FOREIGN KEY ("file_id") REFERENCES "stored_files"("id") ON DELETE RESTRICT ON UPDATE CASCADE;

-- HAND-WRITTEN rule: a version a student sent, and its files, can never be changed or deleted.
CREATE FUNCTION "submission_records_refuse_change"() RETURNS trigger AS $$
BEGIN
  RAISE EXCEPTION '% is read-only: a submitted version cannot be changed or deleted', TG_TABLE_NAME;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER "submission_versions_immutable"
  BEFORE UPDATE OR DELETE ON "submission_versions"
  FOR EACH ROW EXECUTE FUNCTION "submission_records_refuse_change"();
CREATE TRIGGER "submission_files_immutable"
  BEFORE UPDATE OR DELETE ON "submission_files"
  FOR EACH ROW EXECUTE FUNCTION "submission_records_refuse_change"();
