-- Batch 1B-i: application data aligned with the design.
--
--   1. "Why join" is limited to 500 characters
--   2. location  ->  city + state
--   3. one consent timestamp  ->  Terms + Privacy (+ the existing guardian one)
--   4. database-generated references:  GSG-2026-0001 (applications), ENR-1 (enrollments)
--   5. audit log: the actor's role, and the previous / new value
--
-- Existing rows are converted, not lost (see each section). Written by hand
-- because Prisma cannot generate conversions of existing data.

-- ---------------------------------------------------------------------------
-- 1) "Why join": 500 characters. Anything longer in OLD rows is cut at 500
--    (safe while the data is test data).
-- ---------------------------------------------------------------------------
ALTER TABLE "student_applications"
  ALTER COLUMN "why_join" TYPE VARCHAR(500) USING left("why_join", 500);

-- ---------------------------------------------------------------------------
-- 2) location -> city + state.
--    "Chicago, IL" becomes city "Chicago", state "IL" (split at the LAST comma).
--    A value with no comma keeps everything as the city and gets the state
--    "Not given", so no row is left empty.
-- ---------------------------------------------------------------------------
ALTER TABLE "student_profiles"
  ADD COLUMN "city"  VARCHAR(100),
  ADD COLUMN "state" VARCHAR(50);

UPDATE "student_profiles" SET
  "city" = left(
    COALESCE(
      NULLIF(btrim(CASE WHEN position(',' IN "location") > 0
                        THEN left("location", length("location") - position(',' IN reverse("location")))
                        ELSE "location" END), ''),
      btrim("location")
    ),
    100
  ),
  "state" = left(
    COALESCE(
      NULLIF(btrim(CASE WHEN position(',' IN "location") > 0
                        THEN substr("location", length("location") - position(',' IN reverse("location")) + 2)
                        ELSE '' END), ''),
      'Not given'
    ),
    50
  );

ALTER TABLE "student_profiles"
  ALTER COLUMN "city"  SET NOT NULL,
  ALTER COLUMN "state" SET NOT NULL;

ALTER TABLE "student_profiles" DROP COLUMN "location";

-- ---------------------------------------------------------------------------
-- 3) Three agreements, each with its own timestamp:
--    Terms of Use, Privacy Notice, and (already existing) guardian aware.
--    Old rows had ONE timestamp for terms + privacy, so it is copied to both.
-- ---------------------------------------------------------------------------
ALTER TABLE "student_applications" RENAME COLUMN "consent_accepted_at" TO "terms_accepted_at";
ALTER TABLE "student_applications" ADD COLUMN "privacy_accepted_at" TIMESTAMPTZ(3);
UPDATE "student_applications" SET "privacy_accepted_at" = "terms_accepted_at";
ALTER TABLE "student_applications" ALTER COLUMN "privacy_accepted_at" SET NOT NULL;

-- ---------------------------------------------------------------------------
-- 4) References generated by the DATABASE, so every code path that creates an
--    application or enrollment gets one, race-free, with no extra code.
--    Numbers only ever go up (a failed signup can leave a gap - that is normal).
--    The year in an application reference is the year in Chicago (the programme's zone).
-- ---------------------------------------------------------------------------
CREATE SEQUENCE "application_ref_seq" START WITH 1;
CREATE SEQUENCE "enrollment_ref_seq" START WITH 1;

CREATE FUNCTION "next_application_reference"() RETURNS text AS $$
  SELECT 'GSG-' || to_char(now() AT TIME ZONE 'America/Chicago', 'YYYY') || '-' || lpad(nextval('application_ref_seq')::text, 4, '0');
$$ LANGUAGE sql VOLATILE;

CREATE FUNCTION "next_enrollment_reference"() RETURNS text AS $$
  SELECT 'ENR-' || nextval('enrollment_ref_seq')::text;
$$ LANGUAGE sql VOLATILE;

ALTER TABLE "student_applications" ADD COLUMN "reference" VARCHAR(20);
ALTER TABLE "enrollments"          ADD COLUMN "reference" VARCHAR(20);

-- Give existing rows a reference, oldest first (1, 2, 3 ...).
WITH numbered AS (
  SELECT "id", row_number() OVER (ORDER BY "submitted_at", "id") AS n FROM "student_applications"
)
UPDATE "student_applications" AS a
SET "reference" = 'GSG-' || to_char(a."submitted_at" AT TIME ZONE 'America/Chicago', 'YYYY') || '-' || lpad(numbered.n::text, 4, '0')
FROM numbered
WHERE numbered."id" = a."id";

WITH numbered AS (
  SELECT "id", row_number() OVER (ORDER BY "enrolled_at", "id") AS n FROM "enrollments"
)
UPDATE "enrollments" AS e
SET "reference" = 'ENR-' || numbered.n::text
FROM numbered
WHERE numbered."id" = e."id";

-- Continue counting AFTER the existing rows (an empty table starts at 1).
SELECT setval('application_ref_seq', GREATEST(count(*), 1), count(*) > 0) FROM "student_applications";
SELECT setval('enrollment_ref_seq',  GREATEST(count(*), 1), count(*) > 0) FROM "enrollments";

ALTER TABLE "student_applications" ALTER COLUMN "reference" SET DEFAULT "next_application_reference"();
ALTER TABLE "enrollments"          ALTER COLUMN "reference" SET DEFAULT "next_enrollment_reference"();
ALTER TABLE "student_applications" ALTER COLUMN "reference" SET NOT NULL;
ALTER TABLE "enrollments"          ALTER COLUMN "reference" SET NOT NULL;

CREATE UNIQUE INDEX "student_applications_reference_key" ON "student_applications"("reference");
CREATE UNIQUE INDEX "enrollments_reference_key"          ON "enrollments"("reference");

-- ---------------------------------------------------------------------------
-- 5) Audit log: who (their ROLE at the time), and what changed (before / after).
--    Old entries keep these columns empty: the log is append-only, so they
--    cannot be edited afterwards.
-- ---------------------------------------------------------------------------
ALTER TABLE "audit_logs"
  ADD COLUMN "actor_role"     "Role",
  ADD COLUMN "previous_value" JSONB,
  ADD COLUMN "new_value"      JSONB;
